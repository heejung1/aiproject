st.subheader("📝 나만의 진로 계획")

interest = st.text_input(
    "관심 있는 직업이나 분야는?",
    placeholder="예: 디저트 개발, 디자인, 동물"
)

strength = st.text_input(
    "나의 장점은?",
    placeholder="예: 꼼꼼함, 창의력, 소통 능력"
)

if st.button("🌱 나의 진로 다짐 만들기"):
    if interest.strip() and strength.strip():
        st.success(
            f"나는 {strength.strip()}이라는 장점을 살려 "
            f"{interest.strip()} 분야를 탐색하고, "
            "다양한 경험을 통해 나에게 맞는 진로를 찾아갈 거야! 💪"
        )
    else:
        st.warning("관심 분야와 나의 장점을 모두 입력해 줘!")

st.caption(
    "※ 이 결과는 MBTI를 활용한 진로 탐색 참고 자료입니다. "
    "성격 유형만으로 직업 적합성을 판단할 수는 없습니다."
)
st.caption(
    "※ 연봉은 세전 기준의 대략적인 참고 범위이며, "
    "공식 통계값이 아닙니다. 경력·지역·기업·자격에 따라 달라집니다."
)
st.caption(
    "직업별 실제 임금 확인: "
    "고용24·커리어넷의 직업정보를 참고하세요."
)
